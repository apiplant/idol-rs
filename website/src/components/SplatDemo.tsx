import { For, Show, createSignal, onSettled } from "solid-js";
import { SplatView, parsePly } from "../lib/splat";

const DEMOS = [
  { id: "fig-fox", label: "Fox" },
  { id: "fur-egg-chair", label: "Egg chair" },
  { id: "fig-axolotl", label: "Axolotl" },
];

/** The hero: the input picture and its generated splat, live in WebGL2. */
export function SplatDemo() {
  let canvas!: HTMLCanvasElement;
  let view: SplatView | undefined;
  const [current, setCurrent] = createSignal(DEMOS[0].id);
  const [state, setState] = createSignal<"loading" | "ready" | "unsupported">("loading");
  const cache = new Map<string, ArrayBuffer>();
  let want = "";

  async function load(id: string) {
    want = id;
    setCurrent(id);
    setState("loading");
    try {
      let buf = cache.get(id);
      if (!buf) {
        buf = await (await fetch(`/demo/${id}.ply`)).arrayBuffer();
        cache.set(id, buf);
      }
      if (want !== id || !view) return;
      view.autoRotate = true;
      view.load(parsePly(buf));
      setState("ready");
    } catch {
      setState("unsupported");
    }
  }

  onSettled(() => {
    try {
      view = new SplatView(canvas);
    } catch {
      setState("unsupported");
      return;
    }
    load(DEMOS[0].id);
    return () => view?.destroy();
  });

  return (
    <div class="min-w-0">
      <div class="relative aspect-square overflow-hidden rounded-xl border border-line bg-canvas shadow-2xl">
        <canvas ref={canvas} class="absolute inset-0 size-full cursor-grab touch-none active:cursor-grabbing" aria-label="A 3D Gaussian splat generated by idol-rs: drag to orbit" />
        <img src={`/demo/${current()}.webp`} alt="The input picture" class="absolute bottom-3 left-3 size-20 rounded-lg border border-line-strong bg-black object-contain shadow-lg sm:size-24" />
        <Show when={state() === "loading"}>
          <div class="pointer-events-none absolute inset-0 grid place-items-center text-sm text-faint">Loading splat…</div>
        </Show>
        <Show when={state() === "unsupported"}>
          <div class="absolute inset-0 grid place-items-center px-8 text-center text-sm text-muted">
            <span>This browser cannot show the live viewer (WebGL2 is needed). The picture on the left of every demo is the input; the model generates the whole object.</span>
          </div>
        </Show>
        <span class="pointer-events-none absolute top-3 right-3 rounded-full border border-line bg-surface/80 px-2.5 py-1 text-[0.6875rem] text-faint backdrop-blur">drag · scroll</span>
      </div>
      <div class="mt-3 flex flex-wrap gap-2">
        <For each={DEMOS}>
          {(d) => (
            <button
              type="button"
              onClick={() => load(d.id)}
              aria-pressed={current() === d.id ? "true" : "false"}
              class="flex cursor-pointer items-center gap-2 rounded-lg border border-line bg-surface px-2 py-1.5 text-sm text-muted transition-colors hover:border-line-strong hover:text-ink aria-pressed:border-accent-line aria-pressed:bg-accent-soft aria-pressed:text-accent"
            >
              <img src={`/demo/${d.id}.webp`} alt="" class="size-7 rounded bg-black object-cover" />
              {d.label}
            </button>
          )}
        </For>
      </div>
    </div>
  );
}
